-- PostgreSQL: service_types مفتاحه code بلا id، والكود يرتّب بـ rowid (ترتيب الإدخال كما في SQLite).
-- عمود identity باسم rowid يحفظ هذا الترتيب فتعمل «ORDER BY rowid» و«ORDER BY s.rowid» دون تعديل الاستعلامات.
ALTER TABLE service_types ADD COLUMN IF NOT EXISTS rowid BIGINT GENERATED BY DEFAULT AS IDENTITY;
